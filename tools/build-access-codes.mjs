// Build assets/js/access-codes.js from data/CODES-PRIVATE.txt so the static/artifact
// version accepts the issued codes (stored as SHA-256 hashes, never plain).
// The output file is git-ignored: do not commit it.
//   node tools/build-access-codes.mjs
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const txt = fs.readFileSync(path.join(process.env.DATA_DIR || path.join(root, 'data'), 'CODES-PRIVATE.txt'), 'utf8');
const hash = code => crypto.createHash('sha256').update('pi-s2:' + code.toUpperCase()).digest('hex');
const access = [];
for (const m of txt.matchAll(/^(.+?)\t(J\d+)\t(\S+)$/gm)) access.push({ role: 'judge', id: m[2], name: m[1].trim(), hash: hash(m[3]) });
const admin = /^Admin\t-\t(\S+)$/m.exec(txt);
if (admin) access.push({ role: 'admin', id: 'admin', name: 'Admin', hash: hash(admin[1]) });
if (!access.length) throw new Error('No codes found');
fs.writeFileSync(path.join(root, 'assets/js/access-codes.js'),
  `/* Generated by tools/build-access-codes.mjs — hashed login codes. Do not commit. */\nwindow.PI_ACCESS = ${JSON.stringify(access, null, 1)};\n`);
console.log(`assets/js/access-codes.js: ${access.filter(a => a.role === 'judge').length} judges + ${admin ? 1 : 0} admin`);
